SET FOREIGN_KEY_CHECKS = 0;

DROP DATABASE IF EXISTS HEBERGEUR_MC;

CREATE DATABASE IF NOT EXISTS HEBERGEUR_MC
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE HEBERGEUR_MC;

-- -----------------------------------------------------------------------------
-- 1. TABLES DE RÉFÉRENCE (OPTIMISÉES EN TINYINT / SMALLINT UNSIGNED)
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS TYPE_DE_COMPTE (
    TDC_ID TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    TDC_NOM_TYPE_COMPTE VARCHAR(32) NOT NULL,
    PRIMARY KEY (TDC_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ETAT (
    ETA_ID TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    ETA_LIBELLE VARCHAR(32) NOT NULL,
    ETA_DESCRIPTION VARCHAR(255) NULL,
    PRIMARY KEY (ETA_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MODE_DE_JEU (
    MDJ_ID TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    MDJ_LIBELLE VARCHAR(32) NOT NULL,
    MDJ_DESCRIPTION VARCHAR(255) NULL,
    PRIMARY KEY (MDJ_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TYPE_DE_VERSION (
    TDV_ID TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    TDV_LIBELLE VARCHAR(32) NOT NULL,
    TDV_DESCRIPTION VARCHAR(255) NULL,
    PRIMARY KEY (TDV_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS VERSION (
    VER_ID SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    TDV_ID TINYINT UNSIGNED NOT NULL,
    VER_LIBELLE VARCHAR(32) NOT NULL,
    PRIMARY KEY (VER_ID),
    INDEX I_FK_VERSION_TYPE_DE_VERSION (TDV_ID ASC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TYPE_SIGNALEMENT (
    TSGN_ID TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    TSGN_LIBELLE VARCHAR(32) NOT NULL,
    TSGN_DESCRIPTION VARCHAR(255) NULL,
    PRIMARY KEY (TSGN_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS STATUS_AMIS (
    STA_ID TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    STA_LIBELLE VARCHAR(32) NOT NULL,
    PRIMARY KEY (STA_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS TYPE_IMAGE (
    TIMG_ID VARCHAR(32) NOT NULL,
    TIMG_LIBELLE VARCHAR(32) NOT NULL,
    TIMG_CHEMIN_DOSSIER VARCHAR(255) NOT NULL,
    TIMG_DESCRIPTION VARCHAR(255) NULL,
    PRIMARY KEY (TIMG_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS IMAGE (
    IMG_ID INT UNSIGNED NOT NULL AUTO_INCREMENT,
    TIMG_ID VARCHAR(32) NOT NULL,
    IMG_NOM_FICHIER VARCHAR(255) NOT NULL,
    IMG_DATE_PUBLICATION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (IMG_ID),
    INDEX I_FK_IMAGE_TYPE_IMAGE (TIMG_ID ASC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- 2. TABLES UTILISATEURS & SOCIAL
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS UTILISATEUR (
    UTI_ID VARCHAR(36) NOT NULL,
    IMG_ID INT UNSIGNED NULL,
    TDC_ID TINYINT UNSIGNED NOT NULL DEFAULT 1,
    UTI_NOM VARCHAR(24) NOT NULL,
    UTI_EMAIL VARCHAR(100) NOT NULL,
    UTI_DATE_CREATION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UTI_MOT_DE_PASSE VARCHAR(255) NOT NULL,
    UTI_DATE_DERNIERE_CONNEXION DATETIME NULL,
    PRIMARY KEY (UTI_ID),
    UNIQUE INDEX UQ_UTILISATEUR_NOM (UTI_NOM ASC),
    UNIQUE INDEX UQ_UTILISATEUR_EMAIL (UTI_EMAIL ASC),
    INDEX I_FK_UTILISATEUR_IMAGE (IMG_ID ASC),
    INDEX I_FK_UTILISATEUR_TYPE_DE_COMPTE (TDC_ID ASC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS RELATION_UTILISATEUR (
    AMI_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    UTI_ID VARCHAR(36) NOT NULL,
    STA_ID TINYINT UNSIGNED NOT NULL DEFAULT 1,
