    AMI_DATE_DEMANDE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    AMI_DATE_ACCEPTATION DATETIME NULL,
    PRIMARY KEY (AMI_ID),
    INDEX I_FK_RELATION_UTILISATEUR_UTILISATEUR (UTI_ID ASC),
    INDEX I_FK_RELATION_UTILISATEUR_STATUS_AMIS (STA_ID ASC),
    INDEX I_FK_RELATION_UTILISATEUR_DEMANDEUR (UTI_ID_DEMANDEUR ASC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- -----------------------------------------------------------------------------
-- 3. TABLES CATALOGUE (MODPACKS, MODS, PLUGINS & FICHIERS)
