-- 7. CONTRAINTES D'INTÉGRITÉ RÉFÉRENTIELLE (AVEC RÈGLES RGPD & CASCADE)
-- -----------------------------------------------------------------------------

-- Références Version & Images
ALTER TABLE VERSION
    ADD CONSTRAINT FK_VERSION_TYPE_DE_VERSION
    FOREIGN KEY (TDV_ID) REFERENCES TYPE_DE_VERSION (TDV_ID)
    ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE IMAGE
    ADD CONSTRAINT FK_IMAGE_TYPE_IMAGE
    FOREIGN KEY (TIMG_ID) REFERENCES TYPE_IMAGE (TIMG_ID)
    ON DELETE RESTRICT ON UPDATE CASCADE;

-- Références Utilisateur
ALTER TABLE UTILISATEUR
    ADD CONSTRAINT FK_UTILISATEUR_IMAGE
    FOREIGN KEY (IMG_ID) REFERENCES IMAGE (IMG_ID)
    ON DELETE SET NULL ON UPDATE CASCADE,
    ADD CONSTRAINT FK_UTILISATEUR_TYPE_DE_COMPTE
    FOREIGN KEY (TDC_ID) REFERENCES TYPE_DE_COMPTE (TDC_ID)
    ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE RELATION_UTILISATEUR
    ADD CONSTRAINT FK_RELATION_UTILISATEUR_UTILISATEUR
    FOREIGN KEY (UTI_ID) REFERENCES UTILISATEUR (UTI_ID)
    ON DELETE CASCADE ON UPDATE CASCADE,
    ADD CONSTRAINT FK_RELATION_UTILISATEUR_DEMANDEUR
    FOREIGN KEY (UTI_ID_DEMANDEUR) REFERENCES UTILISATEUR (UTI_ID)
    ON DELETE CASCADE ON UPDATE CASCADE,
    ADD CONSTRAINT FK_RELATION_UTILISATEUR_STATUS_AMIS
    FOREIGN KEY (STA_ID) REFERENCES STATUS_AMIS (STA_ID)
    ON DELETE RESTRICT ON UPDATE CASCADE;

-- Références Catalogue (Anonymisation via ON DELETE SET NULL si le créateur supprime son compte)
ALTER TABLE MOD_PACK
    ADD CONSTRAINT FK_MOD_PACK_VERSION
    FOREIGN KEY (VER_ID) REFERENCES VERSION (VER_ID)
    ON DELETE RESTRICT ON UPDATE CASCADE,
    ADD CONSTRAINT FK_MOD_PACK_IMAGE
    FOREIGN KEY (IMG_ID) REFERENCES IMAGE (IMG_ID)
    ON DELETE SET NULL ON UPDATE CASCADE,
    ADD CONSTRAINT FK_MOD_PACK_UTILISATEUR
    FOREIGN KEY (UTI_ID) REFERENCES UTILISATEUR (UTI_ID)
    ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE `MOD`
    ADD CONSTRAINT FK_MOD_UTILISATEUR
    FOREIGN KEY (UTI_ID) REFERENCES UTILISATEUR (UTI_ID)
    ON DELETE SET NULL ON UPDATE CASCADE,
    ADD CONSTRAINT FK_MOD_IMAGE
    FOREIGN KEY (IMG_ID) REFERENCES IMAGE (IMG_ID)
    ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE FICHIER_MOD
    ADD CONSTRAINT FK_FICHIER_MOD_MOD
    FOREIGN KEY (MOD_ID) REFERENCES `MOD` (MOD_ID)
    ON DELETE CASCADE ON UPDATE CASCADE,
    ADD CONSTRAINT FK_FICHIER_MOD_VERSION
    FOREIGN KEY (VER_ID) REFERENCES VERSION (VER_ID)
    ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE PLUGIN
    ADD CONSTRAINT FK_PLUGIN_UTILISATEUR
    FOREIGN KEY (UTI_ID) REFERENCES UTILISATEUR (UTI_ID)
    ON DELETE SET NULL ON UPDATE CASCADE,
    ADD CONSTRAINT FK_PLUGIN_IMAGE
    FOREIGN KEY (IMG_ID) REFERENCES IMAGE (IMG_ID)
    ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE FICHIER_PLUGIN
    ADD CONSTRAINT FK_FICHIER_PLUGIN_PLUGIN
    FOREIGN KEY (PLUG_ID) REFERENCES PLUGIN (PLUG_ID)
    ON DELETE CASCADE ON UPDATE CASCADE;

